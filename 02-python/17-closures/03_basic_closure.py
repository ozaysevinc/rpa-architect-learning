def create_bot():

    bot_name = "Finance Bot"

    def show_bot_name():

        print(f"Running: {bot_name}")

    return show_bot_name


# ==========================================
# 2. Create Bot Function
# ==========================================

bot = create_bot()


# ==========================================
# 3. Run Bot Function
# ==========================================

bot()