# ==========================================
# Python 75 - Mock Example
# ==========================================

from unittest.mock import Mock


# ==========================================
# 1. Create Mock Object
# ==========================================

mock_api = Mock()

# ==========================================
# 2. Set Return Value
# ==========================================

mock_api.return_value = {
    "id": 101,
    "name": "John"
}


# ==========================================
# 3. Call Mock
# ==========================================

result = mock_api()

print(result)
print(result["name"])